/**
 * Check if an email address uses a disposable / temporary email provider.
 *
 * @param email - The email address to check (will be lowercased and trimmed)
 * @returns true if the domain is in the disposable blocklist
 */
export function isDisposableEmail(email: string): boolean {
  const normalized = email.toLowerCase().trim();
  const domain = normalized.split("@")[1];
  if (!domain) return false;

  // Direct match
  if (DISPOSABLE_DOMAINS.has(domain)) return true;

  // Check if it's a subdomain of a blocked domain
  // e.g. "mail.guerrillamail.com" → check "guerrillamail.com"
  const parts = domain.split(".");
  for (let i = 1; i < parts.length; i++) {
    const parent = parts.slice(i).join(".");
    if (DISPOSABLE_DOMAINS.has(parent)) return true;
  }

  return false;
}
